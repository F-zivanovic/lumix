import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { getIconData } from '@iconify/utils';

const ICONS = {
  globe: 'tabler:world',
  'chevron-down': 'tabler:chevron-down',
  'chevron-right': 'tabler:chevron-right',
  tools: 'mdi:tools|flip', // '|flip' = horizontalno ogledalo (prati orijentaciju iz Figme)
  link: 'mdi:link-variant',
  calendar: 'lucide:calendar-days',
  check: 'tabler:check',
  'arrow-filled': 'weui:arrow-filled',
  'cursor-click': 'fluent:cursor-click-24-filled',
  x: 'ri:twitter-x-fill',
  facebook: 'ri:facebook-fill',
  linkedin: 'ri:linkedin-fill',
  instagram: 'ri:instagram-line',
  navigation: 'mdi:navigation',
  pencil: 'mdi:pencil',
  close: 'tabler:x',
  search: 'tabler:search',
  menu: 'tabler:menu-2',
  // Booking stranica (Lucide — imena slojeva iz Figme)
  'search-lucide': 'lucide:search',
  'map-pin': 'lucide:map-pin',
  'grid-2x2': 'lucide:grid-2x2',
  sparkles: 'lucide:sparkles',
  star: 'lucide:star',
  'message-square': 'lucide:message-square',
  'calendar-blank': 'lucide:calendar',
  'chevron-left': 'lucide:chevron-left',
  'locate-fixed': 'lucide:locate-fixed',
  'check-lucide': 'lucide:check',
  sunrise: 'lucide:sunrise',
  sun: 'lucide:sun',
  moon: 'lucide:moon',
  // Stranica salona
  'arrow-left': 'lucide:arrow-left',
  'arrow-up-right': 'lucide:arrow-up-right',
  clock: 'lucide:clock-3',
  building: 'lucide:building',
  image: 'lucide:image',
  video: 'lucide:video',
  // Pricing
  palette: 'lucide:palette',
  'calendar-clock': 'lucide:calendar-clock',
  'badge-check': 'lucide:badge-check',
  plus: 'lucide:plus',
  minus: 'lucide:minus',
};

const sets = {};
const out = {};
for (const [name, spec] of Object.entries(ICONS)) {
  const [ref, flag] = spec.split('|');
  const [prefix, icon] = ref.split(':');
  sets[prefix] ??= JSON.parse(readFileSync(new URL(`../node_modules/@iconify-json/${prefix}/icons.json`, import.meta.url)));
  const data = getIconData(sets[prefix], icon);
  if (!data) throw new Error(`Missing icon ${ref}`);
  const width = data.width ?? sets[prefix].width ?? 16;
  const height = data.height ?? sets[prefix].height ?? 16;
  const body = flag === 'flip' ? `<g transform="translate(${width} 0) scale(-1 1)">${data.body}</g>` : data.body;
  out[name] = { body, width, height };
}
mkdirSync(new URL('../src/components/ui/Icon/', import.meta.url), { recursive: true });
writeFileSync(
  new URL('../src/components/ui/Icon/icons.generated.ts', import.meta.url),
  `// AUTO-GENERATED by scripts/build-icons.mjs — ne menjati ručno.\nexport const icons = ${JSON.stringify(out, null, 2)} as const;\nexport type IconName = keyof typeof icons;\n`
);
console.log('Generated', Object.keys(out).length, 'icons');
